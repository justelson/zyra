const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const { join } = require('node:path')
app.setPath('userData', join(process.env.ZYRA_MEDIA_TEST_ROOT, 'profile'))
let win
const run = code => win.webContents.executeJavaScript(code, true)
const timeout = setTimeout(() => { console.error('Chat media fixture deadline expired'); app.exit(1) }, 150000)
async function until(code, label) {
    const deadline = Date.now() + 12000
    while (Date.now() < deadline) { if (await run(code)) return; await new Promise(done => setTimeout(done, 40)) }
    const state = await run("(()=>{const v=document.querySelector('video');return {ready:v?.readyState,network:v?.networkState,error:v?.error?.message,state:document.querySelector('[data-video-player]')?.dataset.mediaState}})()")
    throw new Error(`Timed out: ${label}: ${JSON.stringify(state)}`)
}
async function click(selector, fraction = 0.5) {
    const point = await run(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.scrollIntoView({block:'nearest'});const r=e.getBoundingClientRect();return{x:r.left+r.width*${fraction},y:r.top+r.height/2}})()`)
    for (const type of ['mouseMove', 'mouseDown', 'mouseUp']) win.webContents.sendInputEvent({ type, x: Math.round(point.x), y: Math.round(point.y), button: 'left', clickCount: 1 })
}
async function screenshot(name) {
    await run("document.querySelector('main').scrollTop=0")
    const point = await run("(()=>{const r=document.querySelector('.video-player-stage').getBoundingClientRect();return{x:r.right-25,y:r.top+25}})()")
    win.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(point.x), y: Math.round(point.y) })
    win.webContents.invalidate()
    await new Promise(done => setTimeout(done, 120))
    await fs.writeFile(join(process.env.ZYRA_QA_SCREENSHOT_DIR, name + '.png'), (await win.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG())
}
app.whenReady().then(async () => {
    try {
        win = new BrowserWindow({ show: false, focusable: false, skipTaskbar: true, width: 1000, height: 820,
            webPreferences: { offscreen: true, backgroundThrottling: false, sandbox: true, contextIsolation: true, nodeIntegration: false } })
        win.webContents.setAudioMuted(true)
        await win.loadURL(process.env.ZYRA_MEDIA_PREVIEW_URL)
        await until("document.querySelector('video')?.readyState>=2&&document.querySelector('audio')?.readyState>=1", 'real video/audio metadata')
        assert.equal(await run("[...document.querySelectorAll('video,audio')].every(m=>!m.controls&&!m.autoplay&&m.paused)"), true)
        assert.equal(await run("!document.querySelector('.video-player-controls [data-video-action=fullscreen]')&&!!document.querySelector('.video-player-stage [data-video-action=fullscreen]')"), true, 'fullscreen belongs on the footage')
        const checkWidth = "(()=>{const body=document.querySelector('.markdown-body').getBoundingClientRect();return [...document.querySelectorAll('.markdown-audio-frame,.markdown-video-frame')].every(e=>Math.abs(e.getBoundingClientRect().width-body.width)<2)&&document.documentElement.scrollWidth<=innerWidth})()"
        assert.equal(await run(checkWidth), true, 'both players fill the chat width')
        await click('[data-video-action="play"]')
        await until("document.querySelector('video').currentTime>0.15", 'custom video Play')
        await click('[data-video-action="play"]')
        await until("document.querySelector('video').paused", 'custom video Pause')
        await click('.video-player .audio-player-seek', 0.55)
        await until("document.querySelector('video').currentTime>3&&!document.querySelector('video').seeking", 'pointer seek')
        const beforeKey = await run("document.querySelector('video').currentTime")
        win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' })
        await until(`document.querySelector('video').currentTime>${beforeKey}`, 'keyboard seek')
        await click('[data-video-action="speed"]'); await click('[data-video-action="mute"]')
        await until("document.querySelector('video').playbackRate===1.25&&document.querySelector('video').muted", 'video speed/mute')
        await click('[data-video-action="play"]'); await until("!document.querySelector('video').paused", 'resume video')
        await click('[data-audio-action="play"]')
        await until("document.querySelector('video').paused&&!document.querySelector('audio').paused", 'audio pauses video')
        await click('[data-video-action="play"]')
        await until("document.querySelector('audio').paused&&!document.querySelector('video').paused", 'video pauses audio')
        await click('[data-video-action="play"]')
        await screenshot('ready-desktop')
        console.log('PASS: decoded video controls and audio/video ownership')
        win.setSize(390, 820); await until('innerWidth===390', 'narrow viewport')
        assert.equal(await run(checkWidth), true, 'both players fit the narrow chat')
        await screenshot('ready-narrow')
        await run("document.querySelector('[aria-label=\"Use light theme\"]').click()")
        await until("document.body.classList.contains('light')", 'light theme')
        await screenshot('ready-light-narrow')
        console.log('PASS: full-width desktop/narrow players and light theme')
        win.setContentSize(1000, 820); await until('innerWidth>=990&&innerWidth<=1010', 'desktop viewport')
        await run("document.querySelector('[aria-label=\"Use dark theme\"]').click();const v=document.querySelector('video');v.src=location.origin+'/__media-preview__/loading.mp4';v.load()")
        await until("document.querySelector('[data-video-player]').dataset.mediaState==='loading'", 'loading state')
        await screenshot('loading-desktop')
        win.setSize(390, 820); await until('innerWidth===390', 'narrow loading viewport'); await screenshot('loading-narrow')
        await until("document.querySelector('video').readyState>=2", 'delayed video recovers')
        console.log('PASS: delayed network loading presentation and recovery')
        await win.loadURL(process.env.ZYRA_MEDIA_PREVIEW_URL + '&state=unavailable')
        await until("document.querySelector('[data-video-player]')?.dataset.mediaState==='error'", 'actual unavailable resource')
        assert.equal(await run("document.querySelectorAll('[data-video-player] video').length===1&&!!document.querySelector('.video-player-recovery a')"), true, 'failure preserves media plus original-file recovery')
        await screenshot('unavailable-narrow')
        win.setContentSize(1000, 820); await until('innerWidth>=990&&innerWidth<=1010', 'desktop error viewport'); await screenshot('unavailable-desktop')
        await click('.video-player-recovery button')
        await until("document.querySelector('video').readyState>=2&&document.querySelector('[data-video-player]').dataset.mediaState==='paused'", 'Retry loads the recovered resource')
        await click('[data-video-action="play"]'); await until("document.querySelector('video').currentTime>0.15", 'recovered video plays')
        await click('[data-video-action="play"]')
        await run("document.querySelector('audio').src=location.origin+'/missing-audio.wav';document.querySelector('audio').load()")
        await until("!!document.querySelector('.audio-player-error')", 'audio error retains controls')
        await screenshot('audio-error-desktop')
        assert.equal(win.isVisible(), false); assert.equal(win.isFocused(), false)
        console.log('PASS: real custom video play/pause, pointer and keyboard seek, speed/mute, shared audio/video ownership, full widths, real error/retry recovery, loading/error/ready screenshots and hidden window')
        clearTimeout(timeout); win.destroy(); app.exit(0)
    } catch (error) { console.error(error); clearTimeout(timeout); win?.destroy(); app.exit(1) }
})
