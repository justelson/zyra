const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const path = require('node:path')
const { writeFile } = require('node:fs/promises')
const directory = process.env.ZYRA_RESOURCE_FIXTURE
app.setPath('userData', path.join(directory, 'profile'))
// Hosted desktops may lack a hardware GPU. Keep real WebGL/canvas assertions
// on a consistent software backend in this disposable, sandboxed process.
if (process.env.CI || process.env.ZYRA_TEST_SOFTWARE_RENDERING === '1') {
    app.commandLine.appendSwitch('use-angle', 'swiftshader')
    app.commandLine.appendSwitch('enable-unsafe-swiftshader')
    app.commandLine.appendSwitch('ignore-gpu-blocklist')
}
if (process.env.ZYRA_RESOURCE_HOST_REDUCED_MOTION === '1') app.commandLine.appendSwitch('force-prefers-reduced-motion')
const timer = setTimeout(() => { console.error('Visualization resource fixture timeout'); app.exit(1) }, 45000)
app.whenReady().then(async () => {
    const hostWidth = Number(process.env.ZYRA_RESOURCE_HOST_WIDTH || 1100)
    assert(Number.isInteger(hostWidth) && hostWidth >= 320 && hostWidth <= 3840)
    const window = new BrowserWindow({ show: false, width: hostWidth, height: 780, webPreferences: { offscreen: true, backgroundThrottling: false, sandbox: true, contextIsolation: true, nodeIntegration: false } })
    // Creation bounds can be clamped to a hosted desktop's work area.
    // These wide-library assertions need a real viewport above 1050px.
    window.setContentSize(1200, 780)
    const messages = []
    window.webContents.on('console-message', event => { messages.push(event.message) })
    window.webContents.on('render-process-gone', (_event, details) => { console.error('Fixture renderer exited:', details) })
    await window.loadURL('about:blank')
    window.webContents.debugger.attach('1.3')
    await window.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
    await window.loadFile(path.join(directory, 'index.html'))
    const evaluate = async code => {
        try { return await window.webContents.executeJavaScript(code) }
        catch (error) { throw new Error(`${error.message}\nExpression: ${code}\nRenderer: ${messages.join('\n')}`) }
    }
    const wait = async expression => {
        for (let attempt = 0; attempt < 160; attempt++) { if (await evaluate(expression)) return; await new Promise(resolve => setTimeout(resolve, 50)) }
        throw new Error(`Timed out: ${expression}\nViewport: ${await evaluate('JSON.stringify({width:innerWidth,workspace:document.querySelector(".assistant-resources-workspace")?.clientWidth})')}\nBody: ${await evaluate('document.body.textContent')}\n${messages.join('\n')}`)
    }
    const mode = name => evaluate(`document.querySelector('[data-fixture-mode="${name}"]').click()`)
    const clickLabel = label => evaluate(`(()=>{const button=[...document.querySelectorAll('button')].find(button=>button.textContent.trim().startsWith(${JSON.stringify(label)}) || button.getAttribute('aria-label')===${JSON.stringify(label)} || button.getAttribute('aria-label')===${JSON.stringify(label)}+' visualization');if(!button)throw new Error('Missing button '+${JSON.stringify(label)});button.click()})()`)
    const capture = async name => {
        console.log(`Checking painted view: ${name}`)
        let image, lastError
        for (let attempt = 0; attempt < 3; attempt++) {
            try { await new Promise(resolve => setTimeout(resolve, 200)); image = await window.webContents.capturePage(); if (!image.isEmpty()) break }
            catch (error) { lastError = error }
        }
        if (!image || image.isEmpty()) throw lastError || new Error(`No painted frame for ${name}`)
        if (process.env.ZYRA_RESOURCE_SCREENSHOTS) await writeFile(path.join(process.env.ZYRA_RESOURCE_SCREENSHOTS, `${name}.png`), image.toPNG())
        return image
    }
    await wait(`innerWidth >= 1050 && document.querySelector('.assistant-resources-workspace')?.clientWidth >= 1050`)
    assert.equal(await evaluate(`matchMedia('(prefers-reduced-motion: reduce)').matches`), false, 'this camera-animation fixture explicitly exercises normal motion')
    await wait(`document.body.textContent.includes('Shapes and a UFO')`)
    assert.equal(await evaluate(`document.querySelectorAll('canvas').length`), 0, 'library thumbnails do not create GPU contexts')
    assert.equal(await evaluate(`document.querySelector('select[aria-label="Visualization scope"]').closest('.assistant-resources-toolbar')!==null`), true, 'scope belongs to the existing header, not a second status row')
    await capture('library')
    await mode('library-unavailable')
    await wait(`document.querySelector('select[aria-label="Visualization scope"]').disabled`)
    assert.equal(await evaluate(`document.querySelector('[role="tooltip"]')===null`), true, 'unavailable details do not occupy a permanent status row')
    await evaluate(`document.querySelector('button[aria-label="Visualization info"]').click()`)
    await wait(`document.querySelector('[role="tooltip"]')?.textContent.includes('unavailable in this client')`)
    await capture('library-info-narrow')
    assert.equal(await evaluate(`(()=>{const tip=document.querySelector('[role="tooltip"]').getBoundingClientRect();return tip.left>=0 && tip.right<=innerWidth})()`), true, 'info tip fits inside the window')
    await evaluate(`document.querySelector('button[aria-label="Visualization info"]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`)
    await wait(`document.querySelector('[role="tooltip"]')===null`)
    await mode('library-narrow')
    await wait(`document.body.textContent.includes('Shapes and a UFO')`)
    await capture('library-narrow')
    assert.equal(await evaluate(`(()=>{const header=document.querySelector('.assistant-resources-toolbar');return header.getBoundingClientRect().width===320 && header.scrollWidth<=header.clientWidth+1})()`), true, 'scope and info fit the real 320px header')
    await evaluate(`(()=>{const select=document.querySelector('select[aria-label="Visualization scope"]');select.value='project';select.dispatchEvent(new Event('change',{bubbles:true}))})()`)
    await wait(`window.fixtureScope==='project'`)
    await mode('library')
    await wait(`document.querySelector('button[role="option"][title^="Shapes and a UFO"]')!==null`)
    await evaluate(`(()=>{window.fixtureFailNextGet=true;document.querySelector('button[role="option"]').click()})()`)
    await wait(`document.body.textContent.includes('Fixture detail failure')`)
    await evaluate(`(()=>{window.fixtureErrorCalls=window.fixtureGetCalls;document.querySelector('button[role="option"][aria-selected="true"]').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}))})()`)
    await wait(`window.fixtureGetCalls>window.fixtureErrorCalls && !document.body.textContent.includes('Fixture detail failure') && !document.body.textContent.includes('Loading preview…')`)
    assert.equal(await evaluate(`window.fixtureGetCalls===window.fixtureErrorCalls+1`), true, 'keyboard selection recovers a different metadata-only resource without Enter/Retry or duplicate fetches')
    await mode('library-unavailable')
    await mode('library')
    await wait(`document.querySelector('button[role="option"][title^="Shapes and a UFO"]')!==null`)
    await evaluate(`(()=>{window.fixturePauseNextGet=true;document.querySelector('button[role="option"]').click()})()`)
    await wait(`typeof window.fixtureReleaseGet==='function'`)
    await evaluate(`(()=>{window.fixturePendingCalls=window.fixtureGetCalls;document.querySelector('[data-fixture-prompt]').click()})()`)
    await wait(`window.fixtureGetCalls>window.fixturePendingCalls && !document.body.textContent.includes('Loading preview…')`)
    assert.equal(await evaluate(`window.fixtureGetCalls===window.fixturePendingCalls+1`), true, 'a refreshed list restarts its invalidated pending detail load exactly once')
    await evaluate(`window.fixtureReleaseGet()`)
    await new Promise(resolve => setTimeout(resolve, 80))
    assert.equal(await evaluate(`document.body.textContent.includes('Loading preview…')`), false, 'the stale completion cannot restore a loading marker')
    await mode('library-unavailable')
    await mode('library')
    await wait(`document.querySelector('button[role="option"][title^="Shapes and a UFO"]')!==null`)
    await evaluate(`document.querySelector('button[role="option"][title^="Shapes and a UFO"]').click()`)
    await wait(`document.body.textContent.includes('Drag to orbit') && document.querySelector('canvas') !== null`)
    await capture('library-scene-detail')
    await evaluate(`window.inspectorCanvas=document.querySelector('canvas')`)
    await evaluate(`document.querySelector('[data-fixture-prompt]').click()`)
    await new Promise(resolve => setTimeout(resolve, 180))
    assert.equal(await evaluate(`document.querySelector('canvas')===window.inspectorCanvas && document.body.textContent.includes('Drag to orbit')`), true, 'metadata refresh preserves loaded canvas/source: ' + await evaluate(`JSON.stringify({connected:window.inspectorCanvas?.isConnected,canvasCount:document.querySelectorAll('canvas').length,text:document.body.textContent})`))
    await clickLabel('Expand')
    await wait(`document.querySelector('[role="dialog"] canvas') !== null && !document.body.textContent.includes('Fixture failed')`)
    await capture('expanded-scene')
    assert.equal(await evaluate(`document.querySelectorAll('[role="dialog"] nav[aria-label="Saved visualizations"] button').length`), 3, 'dedicated viewer keeps one sidebar entry per resource, not per version')
    assert.equal(await evaluate(`(()=>{const panel=document.querySelector('[role="dialog"] [role="tabpanel"]'), canvas=panel.querySelector('canvas');return Math.abs(canvas.getBoundingClientRect().height-panel.getBoundingClientRect().height)<2})()`), true, 'scene occupies the actual full tab surface')
    await evaluate(`document.querySelector('[role="dialog"] button[aria-label="Close visualization details"]').click()`)
    await clickLabel('Visualizations')
    await wait(`document.body.textContent.includes('Traffic comparison')`)
    await mode('details')
    await wait(`document.querySelector('[role="tablist"]') !== null`)
    assert.equal(await evaluate(`document.querySelector('select[aria-label="Visualization version"]').value`), '2')
    await clickLabel('Code')
    await wait(`document.querySelector('[role="tabpanel"]').textContent.includes('Week two')`)
    await evaluate(`(()=>{const select=document.querySelector('select[aria-label="Visualization version"]');select.value='1';select.dispatchEvent(new Event('change',{bubbles:true}))})()`)
    await wait(`document.querySelector('[role="tabpanel"]').textContent.includes('Original snapshot')`)
    assert.equal(await evaluate(`document.querySelector('[role="tabpanel"]').textContent.includes('Week two')`), false, 'switching version updates source, not just badge')
    await clickLabel('Source turn')
    await wait(`window.fixtureOpenedTurn==='fixture-origin-turn'`)
    assert.equal(await evaluate(`window.fixtureOpenedTurn`), 'fixture-origin-turn', 'canonical origin navigates the current local-alias chat turn')
    await clickLabel('Compare versions')
    await wait(`document.querySelector('select[aria-label="Compare against version"]').value==='2'`)
    assert.equal(await evaluate(`document.querySelector('[role="tabpanel"]').getAttribute('aria-labelledby').includes('Code')`), true)
    await clickLabel('Compare versions')
    await clickLabel('Copy code')
    await wait(`window.fixtureCopied?.includes('Original snapshot')`)
    await clickLabel('Copy embed')
    await wait(`window.fixtureCopied?.includes('version="1"')`)
    await clickLabel('Use in chat')
    await wait(`window.fixtureUsed?.version===1 && window.fixtureRouted.some(item=>item.sessionId==='fixture-session' && item.file.content.includes('Version: 1'))`)
    await evaluate(`(()=>{const channel=new BroadcastChannel('zyra:use-visualization');channel.postMessage({requestId:'other-thread-context',detail:{...window.fixtureUsed,threadId:'other-local'}});setTimeout(()=>channel.close(),50)})()`)
    await new Promise(resolve => setTimeout(resolve, 100))
    assert.equal(await evaluate(`window.fixtureRouted.some(item=>item.sessionId==='other-session')`), false, 'inactive composer context is queued, not attached to the selected chat')
    await evaluate(`(()=>{window.fixtureSubscribeOther();return true})()`)
    await wait(`window.fixtureRouted.some(item=>item.sessionId==='other-session' && item.file.content.includes('Version: 1'))`)
    await clickLabel('Versions')
    await wait(`document.querySelector('[role="tabpanel"] ol') !== null`)
    await capture('versions')
    assert.equal(await evaluate(`document.querySelectorAll('[role="tabpanel"] ol li').length`), 2)
    await clickLabel('Preview')
    await wait(`document.querySelector('iframe[data-visualization-ready]') !== null`)
    const frame = window.webContents.mainFrame.frames.find(frame => frame.url.endsWith('/visualization-frame.html'))
    assert(frame)
    assert.equal(await frame.executeJavaScript(`document.body.textContent.includes('Original snapshot')`), true)
    const isolated = await evaluate(`(()=>{try{void document.querySelector('iframe').contentWindow.document;return false}catch{return true}})()`)
    assert.equal(isolated, true, 'saved previews retain opaque isolation')
    await mode('embed')
    await wait(`document.querySelector('[data-visualization-version="1"] iframe[data-visualization-ready]') !== null`)
    assert.equal(await evaluate(`document.querySelector('[data-visualization-version]').dataset.visualizationVersion`), '1', 'chat embed remains pinned even when latest is version two')
    await mode('embed-tall')
    await wait(`document.querySelector('iframe[data-visualization-ready]')!==null`)
    assert(await evaluate(`document.querySelector('iframe').getBoundingClientRect().height`) > 960, 'saved HTML shows the final section beyond its 160px hint')
    await mode('embed-diagram-tall')
    await wait(`document.querySelector('.mermaid-diagram svg')!==null`)
    assert(await evaluate(`document.querySelector('.mermaid-diagram').getBoundingClientRect().height`) > 640, 'tall saved diagrams show their complete intrinsic height')
    await mode('embed-diagram-wide')
    await wait(`document.querySelector('.mermaid-diagram svg')!==null`)
    assert(await evaluate(`(()=>{const e=document.querySelector('.mermaid-diagram');return e.scrollWidth>e.clientWidth && e.scrollHeight<=e.clientHeight+1})()`), 'wide saved diagrams scroll horizontally without vertical clipping or tiny labels')
    await mode('continuity')
    await wait(`document.querySelector('canvas')?.style.opacity==='1' && document.querySelector('iframe[data-visualization-ready]')!==null`)
    await evaluate(`(()=>{window.retainedCanvas=document.querySelector('canvas');window.retainedFrame=document.querySelector('iframe');window.retainedFrameWindow=window.retainedFrame.contentWindow;window.fixtureGetBaseline=window.fixtureGetCalls||0})()`)
    await evaluate(`document.querySelector('[data-fixture-settle]').click()`)
    await new Promise(resolve => setTimeout(resolve, 250))
    for (let prompt=0;prompt<3;prompt++) { await evaluate(`document.querySelector('[data-fixture-prompt]').click()`); await new Promise(resolve => setTimeout(resolve, 70)) }
    assert.equal(await evaluate(`document.querySelector('canvas')===window.retainedCanvas && document.querySelector('iframe')===window.retainedFrame && document.querySelector('iframe').contentWindow===window.retainedFrameWindow`), true, 'settling and new prompt updates retain actual canvas and iframe browsing contexts')
    assert.equal(await evaluate(`(window.fixtureGetCalls||0)===window.fixtureGetBaseline`), true, 'unrelated prompts do not refetch saved visualizations')
    await capture('chat-continuity')
    await mode('loading')
    await wait(`document.querySelector('[data-artifact-phase="creating"]')!==null`)
    const loadingHeight = await evaluate(`document.querySelector('[data-artifact-phase="creating"]').parentElement.parentElement.getBoundingClientRect().height`)
    await evaluate(`document.querySelector('[data-fixture-complete]').click()`)
    await wait(`document.querySelector('canvas')?.style.opacity==='1'`)
    const revealedHeight = await evaluate(`document.querySelector('canvas').closest('[data-visualization-resource-id]').getBoundingClientRect().height`)
    assert(Math.abs(loadingHeight-revealedHeight)<3, 'creation and loaded 3D reserve the same thread space')
    await mode('scene')
    await wait(`document.body.textContent.includes('Drag to orbit') && document.querySelector('canvas').width>0`)
    await new Promise(resolve => setTimeout(resolve, 250))
    const before = await capture('scene')
    const canvasBounds = await evaluate(`document.querySelector('canvas').getBoundingClientRect().toJSON()`)
    const viewport = await evaluate(`({width:innerWidth,height:innerHeight})`)
    const sx = before.getSize().width / viewport.width, sy = before.getSize().height / viewport.height
    const canvasClip = { x: Math.ceil(canvasBounds.x * sx), y: Math.ceil(canvasBounds.y * sy), width: Math.floor(canvasBounds.width * sx), height: Math.floor((canvasBounds.height - 60) * sy) }
    const bitmap = before.toBitmap(), imageWidth = before.getSize().width
    let totalX = 0, totalY = 0, greenPixels = 0
    for (let y = canvasClip.y; y < canvasClip.y + canvasClip.height; y += 2) for (let x = canvasClip.x; x < canvasClip.x + canvasClip.width; x += 2) {
        const offset = (y * imageWidth + x) * 4, blue = bitmap[offset], green = bitmap[offset+1], red = bitmap[offset+2]
        if (green > 50 && green > red * 1.4 && green > blue * 1.05) { totalX += x; totalY += y; greenPixels++ }
    }
    assert(greenPixels > 10, 'the teal sphere is visibly painted, not an empty or stale canvas')
    const spherePoint = { x: Math.round(totalX / greenPixels / sx), y: Math.round(totalY / greenPixels / sy) }
    window.webContents.sendInputEvent({ type: 'mouseDown', ...spherePoint, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...spherePoint, button: 'left', clickCount: 1 })
    await wait(`document.body.textContent.includes('Teal sphere')`)
    await evaluate(`(()=>{const canvas=document.querySelector('canvas');const b=canvas.getBoundingClientRect();const x=b.x+b.width/2,y=b.y+b.height/2;canvas.dispatchEvent(new PointerEvent('pointerdown',{pointerId:7,button:0,clientX:x,clientY:y,bubbles:true}));canvas.dispatchEvent(new PointerEvent('pointermove',{pointerId:7,button:0,clientX:x+90,clientY:y+30,bubbles:true}));canvas.dispatchEvent(new PointerEvent('pointerup',{pointerId:7,bubbles:true}))})()`)
    const after = await capture('scene-orbit')
    await evaluate(`(()=>{window.zoomFrames=0;const request=window.requestAnimationFrame;window.requestAnimationFrame=function(callback){window.zoomFrames++;return request.call(this,callback)};document.querySelector('button[aria-label="Zoom in"]').click()})()`)
    await new Promise(resolve => setTimeout(resolve, 350))
    assert((await evaluate(`window.zoomFrames`)) > 2, 'zoom draws multiple finite animation frames')
    const zoomed = await capture('scene-zoom')
    assert.notDeepEqual(after.crop(canvasClip).toBitmap(), zoomed.crop(canvasClip).toBitmap(), 'animated zoom changes real geometry')
    const settledFrames = await evaluate(`window.zoomFrames`)
    await new Promise(resolve => setTimeout(resolve, 100))
    assert.equal(await evaluate(`window.zoomFrames`), settledFrames, 'camera motion does not keep rendering at idle')
    await evaluate(`document.querySelector('button[aria-label="Reset camera"]').click()`)
    await new Promise(resolve => setTimeout(resolve, 380))
    assert.notDeepEqual(before.crop(canvasClip).toBitmap(), after.crop(canvasClip).toBitmap(), 'real geometry pixels change when orbiting, excluding status text')
    await evaluate(`document.querySelector('[data-fixture-revise]').click()`)
    await wait(`document.body.textContent.includes('Drag to orbit') && !document.body.textContent.includes('Loading 3D')`)
    const revised = await capture('scene-revised')
    assert.notDeepEqual(after.crop(canvasClip).toBitmap(), revised.crop(canvasClip).toBitmap(), 'scene revisions render real updated geometry/materials')
    assert.equal(await evaluate(`document.body.textContent.includes('Scene error') || document.body.textContent.includes('context was lost')`), false, 'revision does not lose reused GL canvas')
    const bounds = await evaluate(`document.querySelector('canvas').getBoundingClientRect().toJSON()`)
    window.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(bounds.x + bounds.width/2), y: Math.round(bounds.y + bounds.height/2), button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(bounds.x + bounds.width/2), y: Math.round(bounds.y + bounds.height/2), button: 'left', clickCount: 1 })
    await mode('narrow')
    await wait(`document.querySelector('[data-fixture-narrow="true"]') !== null`)
    await clickLabel('Code')
    await wait(`document.querySelector('[role="tabpanel"]').textContent.includes('Week two')`)
    await capture('code-narrow')
    assert.equal(await evaluate(`(()=>{const panel=document.querySelector('[data-fixture-narrow="true"]');return panel.getBoundingClientRect().width===320 && panel.scrollWidth<=panel.clientWidth+1})()`), true, 'controls fit a real 320px inspector without horizontal page scrolling')
    console.log('PASS: actual resource hierarchy, version/source switching, pinned embeds, context actions, sandbox isolation, 3D orbit/revision pixels, and narrow layout')
    window.destroy(); clearTimeout(timer); app.quit()
}).catch(error => { console.error(error); clearTimeout(timer); app.exit(1) })
