import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
export async function buildRuntimeSchema({ check = false } = {}) {
  const packageUrl = new URL('../package.json', import.meta.resolve('typebox'));
  const pkg = JSON.parse(await readFile(packageUrl, 'utf8'));
  const output = path.join(root, 'src/runtime/schema/bundled');
  const entries = Object.fromEntries(Object.keys(pkg.exports).map(key => [key === '.' ? 'root' : key.slice(2), key === '.' ? 'typebox' : `typebox/${key.slice(2)}`]));
  // Keep logical node_modules paths in chunk identities when a worktree shares
  // dependencies through a junction. Real filesystem depth is not source input.
  const result = await build({ absWorkingDir: root, entryPoints: entries, bundle: true, splitting: true, preserveSymlinks: true,
    format: 'esm', platform: 'node', target: 'es2022', outdir: output, write: false, legalComments: 'inline',
    chunkNames: 'shared-[hash]', banner: { js: `// Generated by scripts/build-runtime-schema.mjs from MIT-licensed TypeBox ${pkg.version}.` } });
  const generated = new Map(result.outputFiles.map(file => [path.basename(file.path), file.contents]));
  const packageDirectory = new URL('../', import.meta.resolve('typebox'));
  const licenseName = (await readdir(packageDirectory)).find(name => name.toLowerCase() === 'license');
  if (!licenseName) throw new Error('The TypeBox package is missing its license.');
  generated.set('LICENSE', await readFile(new URL(licenseName, packageDirectory)));
  generated.set('manifest.json', Buffer.from(JSON.stringify({ package: 'typebox', version: pkg.version,
    contentHash: [...generated.entries()].sort(([a], [b]) => a.localeCompare(b)).reduce((hash, [name, bytes]) => hash.update(name).update(bytes), createHash('sha256')).digest('hex'),
    entries: Object.fromEntries(Object.entries(entries).map(([name, specifier]) => [specifier, `${name}.js`])) }, null, 2) + '\n'));
  await mkdir(output, { recursive: true });
  for (const [name, contents] of generated) {
    const destination = path.join(output, name);
    if (check) {
      const current = await readFile(destination).catch(() => null);
      if (!current || !Buffer.from(current).equals(Buffer.from(contents))) throw new Error(`Stale runtime schema bundle: ${name}`);
    } else await writeFile(destination, contents);
  }
  for (const name of await readdir(output)) {
    if (generated.has(name)) continue;
    if (!/^shared-[A-Z0-9]+\.js$/.test(name)) throw new Error(`Unexpected runtime schema artifact: ${name}`);
    if (check) throw new Error(`Stale runtime schema artifact: ${name}`);
    await unlink(path.join(output, name));
  }
  console.log(`Runtime schema: TypeBox ${pkg.version}, ${result.outputFiles.length} modules ${check ? 'verified' : 'compiled'}.`);
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildRuntimeSchema({ check: process.argv.includes('--check') });
