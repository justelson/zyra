import assert from 'node:assert/strict';
import { agentServerRequestTimeout } from '../src/agent-server/request-timeouts.mjs';
import { createTuiModelCatalog, unknownTuiModel } from '../src/agent-server/tui-model-catalog.mjs';
import { ZyraAgentServerClient } from '../src/agent-server/client.mjs';

assert.equal(agentServerRequestTimeout('session.request', { type: 'prompt' }), 0);
assert.equal(agentServerRequestTimeout('session.request', { type: 'abort' }), 15_000);
assert.equal(agentServerRequestTimeout('session.join'), 35_000);
assert.equal(agentServerRequestTimeout('runtime.models'), 65_000);
assert.equal(agentServerRequestTimeout('runtime.generateText', { timeoutMs: 5000 }), 10_000);
assert.equal(agentServerRequestTimeout('runtime.generateText', { timeoutMs: Infinity }), 125_000);
assert.equal(agentServerRequestTimeout('session.request', { type: 'compact' }), 120_000);
assert.equal(agentServerRequestTimeout('session.request', { type: 'memory.run' }), 125_000);
assert.equal(agentServerRequestTimeout('session.request', { type: 'agents.wait', payload: { timeoutMs: 60_000 } }), 65_000);
const local = { getAvailable: () => [{ id: 'local-only' }], authStorage: { private: true }, refresh: () => { throw Error('Local discovery must not run'); } };
const { registry, update } = createTuiModelCatalog(local, [{ id: 'opencode/new/future', supportedEfforts: ['native-low', 'native-high'], contextWindow: 32_768 }]);
assert.deepEqual(registry.getAvailable().map(m => m.id), ['new/future']);
assert.deepEqual(registry.find('opencode', 'new/future').zyraSupportedEfforts, ['native-low', 'native-high']);
assert.equal(registry.authStorage, local.authStorage);
registry.refresh();
update([{ id: 'provider/unknown' }]);
assert.equal(registry.getAvailable()[0].reasoning, false);
assert.equal(registry.getAvailable()[0].contextWindow, 0);
assert.equal(registry.find('opencode', 'new/future'), undefined);
assert.deepEqual(unknownTuiModel('future/native/new').zyraSupportedEfforts, []);
assert.equal(unknownTuiModel('future/native/new').contextWindow, 0);
const state = { pending: new Map(), nextRequestId: 1 };
const wire = [];
const socket = { writable: true, write: data => { wire.push(data); return true; } };
const expiring = ZyraAgentServerClient.prototype.requestOnSocket.call(state, socket, 'server.status', {}, { timeoutMs: 100 });
await Promise.all([assert.rejects(expiring, { code: 'AGENT_SERVER_TIMEOUT' }), new Promise(resolve => setTimeout(resolve, 150))]);
assert.equal(state.pending.size, 0, 'expired requests release their pending state while a socket is still live');
assert(socket.writable);
const longRunning = ZyraAgentServerClient.prototype.requestOnSocket.call(state, socket, 'session.request', { type: 'prompt' }, { timeoutMs: 0 });
const pending = [...state.pending.values()][0];
assert.equal(pending.timer, undefined, 'explicit zero retains server-owned long-running requests');
pending.resolve({ ok: true }); state.pending.clear();
assert.deepEqual(await longRunning, { ok: true });
assert.equal(wire.length, 2);
console.log('Client deadlines and host model capabilities: passed');
