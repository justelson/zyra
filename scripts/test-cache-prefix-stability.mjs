import assert from 'node:assert/strict';
import { hiddenTurnContext, skillTurnContext, estimateContextContributions } from '../src/turn-context.mjs';
import { createBrowserToolSet, installBrowserToolTurnCleanup, applyBrowserLoaderOnlyState, BROWSER_TOOLSET_NAMES } from '../src/agent-control/browser-toolset.mjs';
import { installComputerToolTurnCleanup, COMPUTER_TOOLSET_NAMES } from '../src/agent-control/computer-toolset.mjs';
const handlers = new Set();
let active = ['read', 'browser_use', 'tool_search', ...BROWSER_TOOLSET_NAMES, ...COMPUTER_TOOLSET_NAMES];
const session = { getActiveToolNames: () => active, setActiveToolsByName: names => { active = [...names]; }, subscribe: handler => { handlers.add(handler); return () => handlers.delete(handler); } };
installBrowserToolTurnCleanup(session, { preserveLoadedTools: true });
installComputerToolTurnCleanup(session, { preserveLoadedTools: true });
for (const handler of handlers) handler({ type: 'agent_end' });
assert.ok(BROWSER_TOOLSET_NAMES.every(name => active.includes(name)));
assert.ok(COMPUTER_TOOLSET_NAMES.every(name => active.includes(name)));
const tools = createBrowserToolSet({ sessionRef: { current: session } });
const loader = tools.find(tool => tool.name === 'browser_use');
await loader.execute('unload', { action: 'unload' });
assert.ok(BROWSER_TOOLSET_NAMES.every(name => !active.includes(name)), 'explicit unload still removes definitions');
applyBrowserLoaderOnlyState(session);
assert.ok(active.includes('browser_use'));
const memory = hiddenTurnContext('zyra_layered_memory_context', 'Query-specific memory');
assert.equal(memory.display, false);
assert.equal(memory.role, 'custom');
const skillContext = skillTurnContext('/skill:test do it', 'Resolved instructions\n\nUser: do it');
assert.equal(skillContext.customType, 'zyra_skill_context');
assert.deepEqual(skillContext.content, [{ type: 'text', text: 'Resolved instructions' }], 'hidden instructions omit the resolver request suffix so the user prompt is not duplicated');
assert.throws(() => skillTurnContext('/skill:test do it', 'Resolved instructions'), /unexpected request boundary/, 'malformed expansion remains rejected');
assert.equal(skillTurnContext('ordinary prompt', 'ordinary prompt'), null);
const summary = estimateContextContributions({ systemPrompt: 'Stable instructions', messages: [memory], agent: { state: { tools: [] } } });
assert.ok(summary.tokens.memory > 0);
assert.equal(JSON.stringify(summary).includes('Query-specific memory'), false);
console.log('Cache prefix stability: retained schemas, explicit unload, append-only hidden context and private contribution counts: ok');
