import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { CanonicalChatCatalog } from '../src/agent-server/catalog.mjs';
import { getAgentServerPaths } from '../src/agent-server/paths.mjs';
import { forkCanonicalChat, preflightCanonicalChatFork } from '../src/agent-server/chat-fork.mjs';

const temporary = mkdtempSync(path.join(tmpdir(), 'zyra-fork-test-'));
try {
  const project = path.join(temporary, 'project'), directory = path.join(project, '.zyra', 'sessions');
  mkdirSync(directory, { recursive: true });
  const options = { stateDirectory: path.join(temporary, 'state'), channel: 'fork-test' };
  const timestamp = '2026-01-01T00:00:00.000Z';
  const records = [{ type: 'session', version: 3, id: 'source', timestamp, cwd: project }];
  let previous = null;
  const append = (id, value) => { records.push({ ...value, id, parentId: previous, timestamp }); previous = id; };
  append('model', { type: 'model_change', provider: 'test', modelId: 'source-model' });
  append('profile', { type: 'custom', customType: 'zyra.profile.v1', data: { profile: 'builder', source: 'session' } });
  append('config', { type: 'custom', customType: 'zyra.chat-config.v1', data: { model: 'test/source-model', thinking: 'high', profile: 'builder', runtimeMode: 'edits-only', webSearch: false, webFetch: true } });
  append('question', { type: 'message', message: { role: 'user', content: [{ type: 'text', text: 'Inspect this' }], timestamp: 100 } });
  append('call', { type: 'message', message: { role: 'assistant', content: [{ type: 'toolCall', id: 'tool-1', name: 'read', arguments: { path: 'example.ts' } }], provider: 'test', model: 'source-model', timestamp: 101 } });
  append('result', { type: 'message', message: { role: 'toolResult', toolCallId: 'tool-1', toolName: 'read', content: [{ type: 'text', text: 'synthetic contents' }], timestamp: 102 } });
  append('answer', { type: 'message', message: { role: 'assistant', content: [{ type: 'text', text: 'This is the chosen answer.' }], provider: 'test', model: 'source-model', timestamp: 103 } });
  append('later', { type: 'message', message: { role: 'user', content: [{ type: 'text', text: 'Do not include this later turn.' }], timestamp: 104 } });
  const sourcePath = path.join(directory, 'source.jsonl');
  const sourceBytes = `${records.map(record => JSON.stringify(record)).join('\n')}\n`;
  writeFileSync(sourcePath, sourceBytes);
  writeFileSync(path.join(project, 'working.txt'), 'current working file, not historical');
  let catalog = new CanonicalChatCatalog(options);
  catalog.registerProject(project);
  await catalog.index.refreshProject(project);
  const source = await catalog.find('source', { project });
  assert.ok(source, 'real canonical index must discover the source');
  let server = { paths: getAgentServerPaths(options), catalog, sessions: new Map() };
  await assert.rejects(preflightCanonicalChatFork(server, source, { operationId: 'invalid-preflight', entryId: 'missing', worktree: 'isolated' }), /persisted message boundary/);
  await assert.rejects(preflightCanonicalChatFork(server, source, { operationId: 'tool-preflight', entryId: 'call', worktree: 'isolated' }), error => error.code === 'CHAT_FORK_UNSAFE_BOUNDARY');
  assert.equal((await preflightCanonicalChatFork(server, source, { operationId: 'valid-preflight', entryId: 'answer', worktree: 'isolated' })).entryId, 'answer');
  assert.equal(readdirSync(directory).length, 1, 'canonical preflight reads without saving history or requiring a worktree');
  await assert.rejects(forkCanonicalChat(server, source, { operationId: 'unsafe', entryId: 'call' }), error => error.code === 'CHAT_FORK_UNSAFE_BOUNDARY');
  await assert.rejects(forkCanonicalChat(server, source, { operationId: 'no-owner', entryId: 'answer', worktree: 'isolated' }), error => error.code === 'CHAT_FORK_WORKTREE_UNSUPPORTED');
  assert.equal(readdirSync(directory).length, 1, 'invalid boundaries cannot create history');
  const input = { operationId: 'fork-one', entryId: 'assistant-message-zyra-message:assistant:103', title: 'Named fork' };
  const first = await forkCanonicalChat(server, source, input);
  assert.equal(first.profile, 'builder');
  assert.equal(first.effort, 'high');
  assert.equal(first.runtimeMode, 'edits-only');
  assert.equal(first.model, 'test/source-model');
  assert.equal(first.filesystemRestored, false);
  assert.equal(first.worktree, 'shared');
  assert.equal(first.origin.entryId, 'answer');
  assert.equal(first.origin.canonicalChatId, 'source');
  assert.equal(first.chat.titleSource, 'manual');
  assert.equal(first.chat.forkOrigin.entryId, 'answer');
  const forkRecords = readFileSync(first.sessionPath, 'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(forkRecords[0].parentSession, sourcePath);
  assert.deepEqual(forkRecords.filter(record => record.type === 'message').map(record => record.id), ['question', 'call', 'result', 'answer']);
  assert.equal(forkRecords.findLast(record => record.customType === 'zyra.profile.v1').data.profile, 'builder');
  const config = forkRecords.findLast(record => record.customType === 'zyra.chat-config.v1').data;
  assert.equal(config.thinking, 'high'); assert.equal(config.webSearch, false);
  assert.equal(readFileSync(sourcePath, 'utf8'), sourceBytes, 'forking must never open/rewrite the source through an SDK manager');
  assert.equal(readFileSync(path.join(project, 'working.txt'), 'utf8'), 'current working file, not historical');
  assert.equal(server.sessions.size, 0, 'offline history fork must not attach, prompt or start work');
  catalog = new CanonicalChatCatalog(options);
  server = { ...server, catalog };
  assert.equal((await forkCanonicalChat(server, source, input)).canonicalChatId, first.canonicalChatId, 'restart retry returns the same durable fork');
  await assert.rejects(forkCanonicalChat(server, source, { ...input, title: 'Conflicting retry' }), error => error.code === 'CHAT_FORK_OPERATION_CONFLICT');
  await catalog.updateChat(first.canonicalChatId, { title: 'Later title outside the original operation', project: path.join(temporary, 'other-project') });
  assert.equal((await forkCanonicalChat(server, source, input)).chat.title, 'Named fork', 'retry returns the original authorized creation snapshot, not fresh metadata after a Project move');
  const override = await forkCanonicalChat(server, source, { operationId: 'override', entryId: 'answer', model: 'other/target', effort: 'low', profile: 'learner' });
  const overridden = readFileSync(override.sessionPath, 'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(overridden.findLast(record => record.customType === 'zyra.chat-config.v1').data.model, 'other/target');
  assert.equal(overridden.findLast(record => record.customType === 'zyra.profile.v1').data.profile, 'learner');
  const isolatedRoot = path.join(temporary, 'owned-worktree'); mkdirSync(isolatedRoot);
  const isolated = await forkCanonicalChat(server, source, { operationId: 'isolated', entryId: 'answer', worktree: 'isolated' }, { desktopOwned: true, workingRoot: isolatedRoot, scope: { workingRoot: isolatedRoot } });
  assert.equal(isolated.chat.forkPending, true, 'new Desktop forks cannot run before scope confirmation');
  assert.equal(JSON.parse(readFileSync(isolated.sessionPath, 'utf8').split('\n')[0]).cwd, isolatedRoot);
  const oldUpdate = catalog.updateChat.bind(catalog);
  catalog.updateChat = async () => { throw new Error('synthetic registration failure'); };
  const effects = { historyMayExist: false };
  await assert.rejects(forkCanonicalChat(server, source, { operationId: 'uncertain', entryId: 'answer' }, { effects }), /synthetic/);
  assert.equal(effects.historyMayExist, true, 'pending/saved history prohibits workspace rollback');
  catalog.updateChat = oldUpdate;
  await assert.rejects(forkCanonicalChat(server, source, { operationId: 'uncertain', entryId: 'answer' }), error => error.code === 'CHAT_FORK_UNCERTAIN');
  await catalog.updateChat('source', { title: 'New manual title' });
  await assert.rejects(catalog.updateChat('source', { title: 'Stale write', expectedTitle: 'Old title' }), /title changed/);
  assert.equal((await catalog.find('source', { project })).title, 'New manual title');
  console.log('Chat forks: real catalog, exact durable boundary/tool pairing, source immutability, configuration/profile inheritance, restart dedupe, pending scope and fail-closed uncertain completion passed');
} finally { rmSync(temporary, { recursive: true, force: true }); }
