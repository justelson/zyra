import assert from 'node:assert/strict';
import { createChatToolBenchmark } from '../src/benchmarks/chat-tools.mjs';
import { createAssistantActionBatchTool } from '../src/assistant-action-batch-tool.mjs';
const oldSchema = structuredClone(createAssistantActionBatchTool().parameters);
oldSchema.properties.title.maxLength = 72;
const benchmark = createChatToolBenchmark({ actionBatchSchema: oldSchema });
const call = { type: 'message', id: 'entry', message: { role: 'assistant', content: [{ type: 'toolCall', id: 'call', name: 'begin_action_batch', arguments: { title: 'a'.repeat(74) } }] } };
await benchmark.accept(call, 0);
await benchmark.accept(call, 1);
await benchmark.accept({ type: 'message', message: { role: 'assistant', content: [{ type: 'toolCall', id: 'invalid', name: 'begin_action_batch', arguments: { title: '' } }] } }, 0);
const privateValue = { text: 'PRIVATE fixture text with  spaces', status: 'done' };
const result = { type: 'message', message: { role: 'toolResult', toolName: 'agent', toolCallId: 'result', content: [{ type: 'text', text: JSON.stringify(privateValue, null, 2) }, { type: 'image', data: 'base64-fixture' }] } };
await benchmark.accept(result, 0);
await benchmark.accept(result, 1);
await benchmark.accept({ type: 'message', message: { role: 'toolResult', toolName: 'agent', toolCallId: 'truncated', content: [{ type: 'text', text: '{[truncated]' }] } }, 0);
await benchmark.accept({ type: 'message', message: { role: 'toolResult', toolName: 'agent', toolCallId: 'error', isError: true, content: [{ type: 'text', text: 'PRIVATE error' }] } }, 0);
const report = benchmark.finish();
assert.equal(report.marker.recovered, 1);
assert.equal(report.marker.afterAccepted, 1);
assert.equal(report.marker.normalizationFailures, 0);
assert.equal(report.duplicateCalls, 1);
assert.equal(report.duplicateResults, 1);
assert.equal(report.fleet.compared, 1);
assert.equal(report.fleet.changedValues, 0);
assert.equal(report.fleet.excludedErrors, 1);
assert.equal(report.fleet.excludedNonJson, 1);
assert.ok(report.fleet.afterChars < report.fleet.beforeChars);
assert.equal(report.tools.find(t => t.name === 'agent').imageDataChars, 14);
assert.doesNotMatch(JSON.stringify(report), /PRIVATE|base64-fixture|title/);
console.log('Chat tool benchmark: deduplicated offline replay, rejected inputs, text/image separation and private-content-free reports: ok');
