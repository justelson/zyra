import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { ClientResponseTiming } from '../src/diagnostics/client-response-timing.mjs';
import { createClientResponseTimings, CLIENT_TIMING_STORAGE_BYTES } from '../src/diagnostics/client-response-timing-store.mjs';
import { TerminalTimingDisplay } from '../src/diagnostics/terminal-timing-display.mjs';
import { ZyraComponentHost, StaticLinesComponent } from '../src/tui/zyra-tui.mjs';

let clock = 1_000, captures = [];
const timing = new ClientResponseTiming({ now: () => clock, capture: summary => captures.push(summary) });
timing.start('turn:one', 'private-provider/private-model', 'variant:private-effort');
clock = 1_005; timing.dispatch('turn:one');
clock = 1_100; timing.observe('turn:one', { type: 'zyra_server_prompt_accepted', timingStartedAt: 50_000_000 });
clock = 1_130; timing.observe('turn:one', { type: 'model_request_progress', progress: { requestId: 'secret-request', startedAt: 50_000_010, firstEventAt: 50_000_030, firstTextAt: 50_000_045, lastActivityAt: 50_000_045, maxActivityGapMs: 15 } });
timing.observe('turn:one', { type: 'message_update', message: { role: 'assistant', content: [{ type: 'text', text: 'Private response text' }] } });
let row = timing.read()[0];
assert.equal(row.model, 'other'); assert.equal(row.effort, 'unknown');
assert.equal(row.dispatchMs, 5); assert.equal(row.acceptedMs, 100);
assert.equal(row.firstEventMs, 30); assert.equal(row.firstTextMs, 45, 'provider stages use only host timestamps despite unrelated client clock');
assert.equal(row.firstTextReceivedMs, 130); assert.equal(row.firstDisplayMs, null, 'receipt is never substituted for display');
clock = 1_150;
const display = new TerminalTimingDisplay(id => timing.displayed(id));
display.observe({ timingTurnId: 'turn:one', message: { role: 'assistant', content: [{ type: 'text', text: '**Private response** text' }] } });
const output = { columns: 90, rows: 20, isTTY: true, write() {} };
const host = new ZyraComponentHost({ output });
host.onRendered(lines => display.written(lines));
host.components.push(new StaticLinesComponent('answer', ['Private response text']));
host.renderParts(90); host.markRendered(90);
assert.equal(timing.read()[0].firstDisplayMs, null, 'rendering or marking a baseline does not claim an output write');
host.interactive = true; host.renderedLines = []; host.lastContentOutput = ''; host.lastFixedOutput = '';
host.render();
assert.equal(timing.read()[0].firstDisplayMs, 150);
clock = 1_180; timing.observe('turn:one', { type: 'compaction_start' });
clock = 1_200; timing.observe('turn:one', { type: 'compaction_end' });
timing.observe('turn:one', { type: 'auto_retry_start', recoveryKind: 'provider', attempt: 1 });
timing.observe('turn:one', { type: 'auto_retry_start', recoveryKind: 'provider', attempt: 1 });
timing.observe('turn:one', { type: 'zyra_server_turn_completed', outcome: 'completed' });
timing.dispose();
row = timing.read()[0]; assert.equal(row.compactionMs, 20); assert.equal(row.retryCount, 1);
assert.equal(captures.length, 1);
assert.doesNotMatch(JSON.stringify({ row, captures }), /Private response|private-provider|private-model|private-effort|secret-request/);
assert.doesNotMatch(JSON.stringify(captures), /turn:one|startedAt|requests|providerTimingOrigin/);
const missingHost = new ClientResponseTiming({ now: () => clock });
missingHost.start('old:host', 'gpt-6.1-sol', 'high');
missingHost.observe('old:host', { type: 'model_request_progress', progress: { requestId: 'one', startedAt: 100, firstTextAt: 125 } });
assert.equal(missingHost.read()[0].firstTextMs, null);
assert.equal(missingHost.read()[0].requests[0].firstTextMs, 25);
missingHost.dispose();
const directory = await mkdtemp(path.join(tmpdir(), 'zyra-client-timings-'));
try {
  await writeFile(path.join(directory, 'response-timings.json'), JSON.stringify([{ ...row, outcome: 'running', privatePrompt: 'Private history' }]));
  const store = createClientResponseTimings(directory, { now: () => clock }); await store.ready;
  assert.equal(store.recorder.read()[0].outcome, 'unfinished');
  for (let i = 0; i < 205; i++) { clock++; store.recorder.start(`turn:${i}`, 'gpt-6.1-sol', 'high'); store.recorder.finish(`turn:${i}`, 'completed'); }
  await store.flush();
  assert.equal(store.recorder.read().length, 200);
  assert((await stat(store.file)).size < CLIENT_TIMING_STORAGE_BYTES);
  assert.doesNotMatch(await readFile(store.file, 'utf8'), /Private history|privatePrompt/);
  await store.dispose();
} finally { await rm(directory, { recursive: true, force: true }); }
console.log('Client response timing: host/client clock separation, actual terminal writes, missing stages, privacy, bounded local persistence and retention passed');

const recovered = new ClientResponseTiming();
recovered.start('turn:offline', 'gpt-6.1-sol', 'high');
recovered.reconcile({ latestTurn: { id: 'turn:offline', state: 'completed' } });
assert.equal(recovered.read()[0].outcome, 'completed');
assert.equal(recovered.read()[0].completedMs, null, 'snapshot cannot invent an unobserved completion time');
recovered.start('turn:failed', 'gpt-6.1-sol', 'high');
recovered.reconcile({ latestTurn: { id: 'turn:failed', state: 'error' } });
assert.equal(recovered.read().find(row => row.turnId === 'turn:failed').outcome, 'failed');
recovered.dispose();
