import assert from 'node:assert/strict';
import { HarnessToolOutput } from '../src/harness-tool-output.mjs';

const offsets = new Map(), published = [];
const output = new HarnessToolOutput(offsets, parts => published.push(parts));
const delta = (id, text) => ({ id, type: 'session.text.delta', data: { assistantMessageID: 'a', ordinal: 0, delta: text } });
assert.equal(output.delta(delta('before-baseline', 'prefix missing')), true, 'a missed prefix triggers one bounded snapshot');
assert.equal(output.delta(delta('before-baseline-2', 'more')), false, 'unknown token bursts cannot cause a read per token');
output.snapshot([{ id: 'a', content: [{ type: 'text', text: 'Hello' }] }]);
output.delta(delta('already-snapshotted', 'Hello'));
assert.equal(output.content()[0].text, 'Hello', 'a snapshot baseline cannot receive the same in-flight delta twice');
output.snapshot([{ id: 'a', content: [{ type: 'text', text: 'Hello world' }] }]);
assert.equal(output.content()[0].text, 'Hello world', 'duplicate event IDs cannot duplicate text');
output.snapshot([{ id: 'a', content: [{ type: 'text', text: 'Hello' }] }]);
assert.equal(output.content()[0].text, 'Hello world', 'a stale snapshot cannot retract streamed text');
output.commit();
const next = new HarnessToolOutput(offsets);
next.snapshot([{ id: 'a', content: [{ type: 'text', text: 'Hello world after tool' }] }]);
assert.equal(next.content()[0].text, ' after tool', 'a tool boundary cannot repeat preceding commentary');
assert.ok(published.length >= 2);
const deltas = [], streamed = new HarnessToolOutput(new Map(), undefined, (type, text) => deltas.push([type, text]));
streamed.delta({ type: 'session.text.started', data: { assistantMessageID: 'a', ordinal: 0 } });
streamed.delta(delta('new', 'Hello'));
streamed.snapshot([{ id: 'a', content: [{ type: 'text', text: 'Hello world' }] }]);
assert.equal(streamed.content()[0].text, 'Hello', 'live SSE prefixes cannot be overtaken by snapshots');
streamed.delta(delta('second', ' world'));
streamed.delta(delta('second', ' world'));
assert.deepEqual(deltas, [['text', 'Hello'], ['text', ' world']], 'stream deltas publish incrementally without rebuilding preceding output');
streamed.disconnected();
streamed.snapshot([{ id: 'a', content: [{ type: 'text', text: 'Hello world recovered' }] }]);
assert.equal(streamed.content()[0].text, 'Hello world recovered', 'disconnect falls back to authoritative snapshots');
const mixed = new HarnessToolOutput(new Map());
mixed.delta({ type: 'session.reasoning.started', data: { assistantMessageID: 'b', ordinal: 0 } });
mixed.delta({ type: 'session.reasoning.delta', data: { assistantMessageID: 'b', ordinal: 0, delta: 'Reason' } });
mixed.delta({ type: 'session.text.started', data: { assistantMessageID: 'b', ordinal: 0 } });
mixed.delta({ type: 'session.text.delta', data: { assistantMessageID: 'b', ordinal: 0, delta: 'Answer' } });
assert.deepEqual(mixed.content(), [{ type: 'thinking', thinking: 'Reason' }, { type: 'text', text: 'Answer' }], 'text and reasoning have independent native ordinal counters');
mixed.snapshot([{ id: 'b', time: { completed: 1 }, content: [{ type: 'reasoning', text: 'Reason' }, { type: 'tool', id: 'call' }, { type: 'text', text: 'Answer' }] }]);
mixed.commit();
const resumed = new HarnessToolOutput(mixed.offsets);
resumed.snapshot([{ id: 'b', content: [{ type: 'reasoning', text: 'Reason' }, { type: 'tool', id: 'call' }, { type: 'text', text: 'Answer continued' }] }]);
assert.deepEqual(resumed.content(), [{ type: 'thinking', thinking: '' }, { type: 'text', text: ' continued' }], 'snapshot offsets count each part type independently across tool boundaries');
console.log('OpenCode output: missed-prefix recovery, bounded snapshot wakeups, immediate deltas, event deduplication, stale snapshots and tool-boundary offsets passed.');
