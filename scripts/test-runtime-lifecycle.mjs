import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { ZyraAgentServer } from '../src/agent-server/server.mjs';
import { ZyraAgentServerClient } from '../src/agent-server/client.mjs';
import { readRuntimeRevision, RUNTIME_ACTIVATION_VERSION } from '../src/agent-server/runtime-revision.mjs';

const directory = await mkdtemp(path.join(os.tmpdir(), 'zyra-runtime-lifecycle-'));
const root = path.join(directory, 'runtime');
const servers = [], clients = [];
try {
  await mkdir(path.join(root, 'src'), { recursive: true });
  await writeFile(path.join(root, 'package.json'), '{}');
  await writeFile(path.join(root, 'src/fixture.mjs'), 'export const version = 2;');
  const desired = await readRuntimeRevision(root);
  const options = { root, stateDirectory: path.join(directory, 'state'), channel: 'lifecycle', endpoint: 0, desktopAuthorityToken: 'synthetic-authority' };
  let server = new ZyraAgentServer(options); servers.push(server); await server.start();
  server.runtimeRevision = 'a'.repeat(64);
  const summary = { activeRequests: 1, backgroundWorkActive: false, attention: null, latestTurn: { state: 'running' } };
  server.sessions.set('busy', { summary: () => summary, dispose() {}, detach() {} });
  let retirements = 0;
  let retired;
  const installRetirement = () => server.once('retire', () => { retirements++; retired = server.stop(); });
  installRetirement();
  const client = new ZyraAgentServerClient({ ...options, surface: 'desktop', authorities: ['desktop-control'], authorityProof: 'synthetic-authority', heartbeat: false });
  clients.push(client);
  let starts = 0;
  client.startServer = () => { starts++; void retired.then(async () => { server = new ZyraAgentServer(options); servers.push(server); await server.start(); }); };
  await client.connect();
  const oldInstance = client.instance.instanceId;
  const status = await client.refreshRuntimeStatus();
  assert.equal(status.expectedRuntimeRevision, desired, 'installed code and running code have distinct identities');
  assert.equal(status.instance.runtimeRevision, 'a'.repeat(64));
  assert.equal(status.activity.activeTurns, 1);
  assert.equal(status.activity.requests, 1, 'in-flight worker cleanup is reported as well as foreground turns');
  assert.equal(status.updatePending, true);
  await client.activateRuntimeUpdate();
  assert.equal(retirements, 0, 'explicit activation cannot cancel running work');
  assert.equal(starts, 0);
  assert.equal(client.socket.writable, true, 'a deferred update preserves live observation');
  summary.activeRequests = 0; summary.latestTurn = { state: 'completed' }; summary.backgroundWorkActive = true;
  await client.activateRuntimeUpdate();
  assert.equal(retirements, 0, 'background processes also block replacement');
  assert.equal(client.connectionStatus.activity.backgroundChats, 1);
  assert.equal(client.connectionStatus.activity.requests, 0, 'the status request does not count itself');
  assert.ok(!JSON.stringify(client.connectionStatus).includes('synthetic-authority'));
  summary.backgroundWorkActive = false; summary.attention = 'approval';
  await client.activateRuntimeUpdate();
  assert.equal(retirements, 0, 'pending attention blocks replacement');
  summary.attention = null;
  server.sessions.clear();
  const memoryController = new AbortController();
  server.memoryQueue.active = { session: {}, controller: memoryController };
  await client.activateRuntimeUpdate();
  assert.equal(retirements, 0, 'active memory consolidation also blocks replacement');
  assert.equal(memoryController.signal.aborted, false, 'activation cannot abort background maintenance');
  assert.equal(client.connectionStatus.activity.requests, 1, 'maintenance is visible as an in-flight request');
  server.memoryQueue.active = null;
  // These servers intentionally share the test PID. Supply a dead predecessor
  // PID so the real replacement handshake never waits for this test to exit.
  const descriptor = JSON.parse(readFileSync(server.paths.descriptorFile, 'utf8'));
  writeFileSync(server.paths.descriptorFile, JSON.stringify({ ...descriptor, pid: 2147483646 }));
  let disconnects = 0;
  client.on('disconnect', () => disconnects++);
  const one = client.activateRuntimeUpdate();
  const two = client.activateRuntimeUpdate();
  await Promise.all([one, two]);
  assert.equal(retirements, 1, 'simultaneous actions share one retirement');
  assert.equal(starts, 1);
  assert.equal(disconnects, 1, 'Desktop must invalidate idle worker bindings when an old server is retired');
  assert.equal(client.connectionStatus.instance.runtimeRevision, desired);
  assert.equal(client.connectionStatus.expectedRuntimeRevision, desired);
  assert.notEqual(client.instance.instanceId, oldInstance, 'activation proves a replacement actually started');
  assert.equal(client.connectionStatus.updatePending, undefined);
  assert.equal(client.connectionStatus.phase, 'ready');
  await client.activateRuntimeUpdate();
  assert.equal(starts, 1, 'already-current activation is an observation, not another restart');
  await assert.rejects(client.request('server.retire', { activationVersion: RUNTIME_ACTIVATION_VERSION, expectedRevision: desired, expectedInstanceId: oldInstance }), { code: 'AGENT_SERVER_INSTANCE_CHANGED' });
  const observer = new ZyraAgentServerClient({ ...options, autoStart: false, verifyRuntimeRevision: false, heartbeat: false, requiredMethods: ['server.status'] });
  clients.push(observer); await observer.connect();
  await assert.rejects(observer.activateRuntimeUpdate(), { code: 'AGENT_SERVER_AUTH_FAILED' });
  assert.equal(starts, 1, 'read-only observers never gain activation authority');
  observer.close();
  await writeFile(path.join(root, 'src/fixture.mjs'), 'export const version = 3;');
  installRetirement();
  const beforeWrong = JSON.parse(readFileSync(server.paths.descriptorFile, 'utf8'));
  writeFileSync(server.paths.descriptorFile, JSON.stringify({ ...beforeWrong, pid: 2147483646 }));
  client.startServer = () => { starts++; void retired.then(async () => {
    server = new ZyraAgentServer(options); servers.push(server); await server.start(); server.runtimeRevision = 'f'.repeat(64);
  }); };
  await assert.rejects(client.activateRuntimeUpdate(), { code: 'AGENT_SERVER_UPGRADE_REQUIRED' });
  assert.equal(client.connectionStatus.connection, 'connected', 'a compatible wrong-revision replacement stays observable');
  assert.equal(client.connectionStatus.phase, 'waiting');
  assert.equal(client.socket.writable, true);
  await client.refreshRuntimeStatus();
  assert.equal(client.connectionStatus.instance.instanceId, server.instanceId, 'refresh must not be pinned to the retired predecessor');
  assert.equal(client.connectionStatus.updatePending, true);
  await writeFile(path.join(root, 'src/fixture.mjs'), 'export const version = 4;');
  installRetirement();
  const beforeMissing = JSON.parse(readFileSync(server.paths.descriptorFile, 'utf8'));
  writeFileSync(server.paths.descriptorFile, JSON.stringify({ ...beforeMissing, pid: 2147483646 }));
  client.startServer = () => { starts++; void retired.then(async () => {
    server = new ZyraAgentServer(options); servers.push(server);
    const state = server.state.bind(server);
    server.state = input => { const result = state(input); result.methods = result.methods.filter(method => method !== 'runtime.prepare'); return result; };
    await server.start();
  }); };
  await assert.rejects(client.activateRuntimeUpdate(), { code: 'AGENT_SERVER_UPGRADE_REQUIRED' });
  assert.equal(client.socket, null, 'an incompatible replacement is really disconnected, not a writable orphan');
  assert.equal(client.connectionStatus.connection, 'disconnected');
  assert.equal(client.connectionStatus.phase, 'failed');
  console.log('Runtime lifecycle: explicit activation, blockers, exact instance, deduplication and verified replacement passed');
} finally {
  clients.forEach(client => client.close());
  for (const server of servers) await server.stop();
  await rm(directory, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
}
