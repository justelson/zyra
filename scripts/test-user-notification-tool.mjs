import assert from 'node:assert/strict';
import { createUserNotificationTool, normalizeUserNotification } from '../src/user-notification-tool.mjs';
import { ChatNotificationContent } from '../src/agent-server/chat-notification-content.mjs';

const received = [];
const tool = createUserNotificationTool(async notice => received.push(notice));
assert.equal(tool.executionMode, 'sequential');
await tool.execute('owned-call', { kind: 'completed', title: 'Preview build ready', body: 'Checks passed. Open the installer from Downloads.' });
assert.deepEqual(received, [{ id: 'owned-call', kind: 'completed', title: 'Preview build ready', body: 'Checks passed. Open the installer from Downloads.' }]);
const abort = new AbortController(); abort.abort();
await assert.rejects(tool.execute('stopped', { kind: 'completed', title: 'Stopped', body: 'Not delivered.' }, abort.signal));
assert.equal(received.length, 1);
assert.throws(() => normalizeUserNotification({ kind: 'arbitrary', title: 'Bad', body: 'Bad' }));
assert.match(normalizeUserNotification({ kind: 'input', title: 'Choose target', body: 'key sk-' + 'z'.repeat(24) }).body, /REDACTED_SECRET/);
assert.equal(normalizeUserNotification({ kind: 'update', title: 'Test', body: 'password=private Bearer private-token' }).body, 'password=[REDACTED_SECRET] Bearer [REDACTED_SECRET]');
const content = new ChatNotificationContent();
assert.equal(content.observe('turn', { type: 'session_notification', ...received[0] }, 1000), null, 'completion preparation does not notify early');
assert.equal(content.take('completed', {}).title, 'Preview build ready');
assert.equal(content.take('completed', {}), null, 'a draft is consumed exactly once');
content.observe('turn', { type: 'message_end', message: { role: 'assistant', stopReason: 'stop', content: [{ type: 'text', text: '**Fixed tool loading.**\nAll checks passed.' }] } }, 1000);
assert.equal(content.take('completed', {}).body, 'Fixed tool loading. All checks passed.');
content.observe('next-turn', { type: 'agent_start' }, 2000);
assert.equal(content.take('completed', {}), null, 'a previous turn cannot supply stale notification content');
const input = content.take('input', { questions: [{ header: 'Deployment', question: 'Deploy to preview or production?' }] });
assert.deepEqual(input, { title: 'Deployment', body: 'Deploy to preview or production?' });
assert.deepEqual(content.take('approval', { title: 'Approve browser access', detail: 'Observe the requested Chrome tab.' }), { title: 'Approve browser access', body: 'Observe the requested Chrome tab.' });
const update = { type: 'session_notification', kind: 'update', title: 'Tests passed', body: 'Packaging is running.' };
assert.ok(content.observe('next-turn', update, 2000));
assert.equal(content.observe('next-turn', update, 3000), null, 'routine update spam is bounded');
assert.ok(content.observe('next-turn', update, 33000));
assert.ok(content.observe('next-turn', update, 64000));
assert.equal(content.observe('next-turn', update, 95000), null, 'there are at most three milestone notices per turn');
console.log('Notification tool: current-chat content, cancellation, redaction, actual-completion staging, useful fallback, question text, stale-turn reset and bounded milestones passed.');
